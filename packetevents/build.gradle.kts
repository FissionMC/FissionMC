// Plain Gradle build of the vendored PacketEvents api + netty-common (upstream's buildSrc conventions are not vendored).
// Sources stay untouched under packetevents/api and packetevents/netty-common; local changes go to upstream/patches/packetevents.
val adventure = "4.26.1"
val genDir = layout.buildDirectory.dir("generated/pe-version")

val generatePeVersion by tasks.registering {
    outputs.dir(genDir)
    doLast {
        val f = genDir.get().file("com/github/retrooper/packetevents/util/PEVersions.java").asFile
        f.parentFile.mkdirs()
        f.writeText("""
            package com.github.retrooper.packetevents.util;
            /** Generated by FissionMC's build (upstream generates this with its buildSrc task). */
            public final class PEVersions {
                public static final String RAW = "2.0.0-fission";
                public static final java.time.Instant BUILD_TIMESTAMP = java.time.Instant.EPOCH;
                public static final PEVersion CURRENT = new PEVersion(2, 0, 0, "fission");
                public static final PEVersion UNKNOWN = new PEVersion(0, 0, 0);
                private PEVersions() { throw new IllegalStateException(); }
            }
        """.trimIndent())
    }
}

the<SourceSetContainer>()["main"].java.srcDirs(
    "api/src/main/java", "netty-common/src/main/java", genDir,
    "patch/adventure-text-serializer-gson/src/main/java", "patch/adventure-text-serializer-legacy/src/main/java")
the<SourceSetContainer>()["main"].resources.srcDir("resources")   // generated mapping resources, see upstream/packetevents-resources.md
// Upstream's patched adventure serializers (packetevents/patch) have the SAME class names as adventure's own and were compiled against
// adventure 4.x; PacketEvents needs them to compile (e.g. showAchievementToComponent). On the backend they must NOT be on the class
// path: they would shadow paper-api's adventure 5.x classes and break every Component serialization (NoClassDefFoundError
// net/kyori/adventure/util/Buildable$Builder as soon as a relayed player joins). So the normal jar leaves them out and `patchJar`
// carries them; only the master (run, tests, clientProbe) adds `patchJar` to its class path.
val mainOutput = the<SourceSetContainer>()["main"].output
val shadowing = listOf(
    "net/kyori/adventure/text/serializer/gson/GsonComponentSerializer*.class", "net/kyori/adventure/text/serializer/gson/SerializerFactory*.class",
    "net/kyori/adventure/text/serializer/gson/ShowItemSerializer*.class", "net/kyori/adventure/text/serializer/gson/ShowEntitySerializer*.class",
    "net/kyori/adventure/text/serializer/gson/StyleSerializer*.class", "net/kyori/adventure/text/serializer/gson/ComponentSerializerImpl*.class",
    "net/kyori/adventure/text/serializer/legacy/**", "net/kyori/adventure/text/serializer/json/legacyimpl/NBTLegacyHoverEventSerializerImpl*.class")
tasks.named<Jar>("jar") { exclude(shadowing) }
tasks.register<Jar>("patchJar") {
    archiveClassifier = "adventure-patch"
    from(mainOutput)
    include(shadowing)
}
tasks.withType<JavaCompile>().configureEach {
    dependsOn(generatePeVersion)
    options.compilerArgs.add("-Xlint:none")
    options.release = 21
}
tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach { dependsOn(generatePeVersion) }

dependencies {
    api(platform("io.netty:netty-bom:4.2.20.Final"))
    api("io.netty:netty-buffer"); api("io.netty:netty-transport")
    api("net.kyori:adventure-api:$adventure"); api("net.kyori:adventure-nbt:$adventure")
    api("net.kyori:adventure-key:$adventure")
    api("net.kyori:adventure-text-serializer-gson:$adventure") { exclude(group = "net.kyori", module = "adventure-text-serializer-commons") }
    api("net.kyori:adventure-text-serializer-json-legacy-impl:$adventure"); api("net.kyori:adventure-text-serializer-commons:$adventure")
    api("net.kyori:adventure-text-serializer-legacy:$adventure")
    api("net.kyori:adventure-text-logger-slf4j:$adventure")
    api("com.google.code.gson:gson:2.11.0")
    api("org.jspecify:jspecify:1.0.0"); api("org.jetbrains:annotations:26.0.2")
    api("org.checkerframework:checker-qual:3.41.0")
}
