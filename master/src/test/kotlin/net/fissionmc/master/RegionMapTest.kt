package net.fissionmc.master

import io.netty.buffer.Unpooled
import net.fissionmc.master.region.RegionMap
import net.fissionmc.protocol.*
import java.util.Properties
import kotlin.test.*

class RegionMapTest {
    private fun props(vararg kv: String) = Properties().apply { kv.toList().chunked(2).forEach { setProperty(it[0], it[1]) } }
    private val ow = "minecraft:overworld"
    private fun split() = RegionMap.parse(props("regions.overworld", "min,min,0,max:backend-a;0,min,max,max:backend-b", "regions.the_nether", "*:backend-a", "regions.default", "backend-a"))

    @Test fun `lookup follows the rectangles, the star rule and the default`() {
        val m = split()
        assertEquals("backend-a", m.owner(ow, -1, 500)); assertEquals("backend-b", m.owner(ow, 0, 500)); assertEquals("backend-b", m.owner(ow, 30_000_000, -30_000_000))
        assertEquals("backend-a", m.owner("minecraft:the_nether", 123, 456)); assertEquals("backend-a", m.owner("minecraft:the_end", 1, 1), "default owner for the rest")
        assertTrue(m.enabled); assertFalse(RegionMap.parse(Properties()).enabled); assertNull(RegionMap.OFF.owner(ow, 0, 0))
    }

    @Test fun `a map that leaves a hole or overlaps is refused with the place`() {
        val hole = assertFailsWith<IllegalArgumentException> { RegionMap.parse(props("regions.overworld", "min,min,0,max:backend-a;100,min,max,max:backend-b")) }
        assertTrue(hole.message!!.contains("nobody owns"), hole.message)
        val overlap = assertFailsWith<IllegalArgumentException> { RegionMap.parse(props("regions.overworld", "min,min,100,max:backend-a;0,min,max,max:backend-b")) }
        assertTrue(overlap.message!!.contains("overlap"), overlap.message)
        val badNumber = assertFailsWith<Exception> { RegionMap.parse(props("regions.overworld", "min,min,x,max:backend-a")) }
        assertNotNull(badNumber)
        assertFailsWith<IllegalArgumentException> { RegionMap.parse(props("regions.overworld", "min,min,0:backend-a")) }
        // a 2x2 grid is fine
        val grid = RegionMap.parse(props("regions.overworld", "min,min,0,0:a;0,min,max,0:b;min,0,0,max:c;0,0,max,max:d"))
        assertEquals(listOf("a", "b", "c", "d"), listOf(grid.owner(ow, -1, -1), grid.owner(ow, 1, -1), grid.owner(ow, -1, 1), grid.owner(ow, 1, 1)))
    }

    @Test fun `hysteresis keeps a player on its backend until it is margin blocks inside the next region`() {
        val m = split()
        assertEquals("backend-a", m.ownerWithHysteresis(ow, 3, 0, "backend-a", 8), "3 blocks over the border: not yet")
        assertEquals("backend-a", m.ownerWithHysteresis(ow, 7, 0, "backend-a", 8))
        assertEquals("backend-b", m.ownerWithHysteresis(ow, 8, 0, "backend-a", 8))
        assertEquals("backend-b", m.ownerWithHysteresis(ow, -3, 0, "backend-b", 8), "and back: -3 is not far enough inside a")
        assertEquals("backend-a", m.ownerWithHysteresis(ow, -9, 0, "backend-b", 8))
        assertEquals("backend-a", m.ownerWithHysteresis(ow, -100, 0, "backend-a", 8))
        assertEquals("backend-b", m.ownerWithHysteresis(ow, 100, 0, null, 8), "no current backend: the owner at the point")
    }

    @Test fun `the border strip is generated by the lower backend id, the rest by its owner`() {
        val m = split()
        assertEquals("backend-a", m.generationOwner(ow, -5, 0, 1)); assertEquals("backend-b", m.generationOwner(ow, 5, 0, 1))
        assertEquals("backend-a", m.generationOwner(ow, -1, 0, 1)); assertEquals("backend-a", m.generationOwner(ow, 0, 0, 1), "chunk 0 is b's but touches the border: a generates it")
        assertEquals("backend-b", m.generationOwner(ow, 1, 0, 1)); assertEquals("backend-b", m.generationOwner(ow, 0, 0, 0), "no strip: the owner")
        assertNull(RegionMap.OFF.generationOwner(ow, 0, 0, 1))
    }

    @Test fun `the default owner travels to the backends as a rule for the dimension star`() {
        val rules = split().toRules()
        assertTrue(rules.any { it.dimension == "*" && it.backend == "backend-a" }, rules.toString())
        assertEquals(setOf(ow, "minecraft:the_nether", "*"), rules.map { it.dimension }.toSet())
    }

    @Test fun `region messages survive the wire`() {
        val reg = MessageRegistry.core().registerRegionMessages()
        fun rt(m: NodeMessage): NodeMessage { val b = Unpooled.buffer(); reg.encode(m, b); return reg.decode(b).also { assertEquals(0, b.readableBytes()) } }
        val map = RegionMap("backend-b", split().toRules()); assertEquals(map, rt(map))
        assertEquals(GenerateChunk(ow, -3, 7), rt(GenerateChunk(ow, -3, 7)))
        assertEquals(PlayerPosition(1, 2, ow, -100, 55), rt(PlayerPosition(1, 2, ow, -100, 55)))
        val h = rt(EntityHandover("backend-a", "backend-b", ow, listOf(EntityBlob(2, 1, 2, byteArrayOf(1, 2, 3))))) as EntityHandover
        assertEquals("backend-b", h.toBackend); assertContentEquals(byteArrayOf(1, 2, 3), h.blobs.single().bytes)
        val a = rt(EntityHandoverAck("backend-a", listOf(1L, 2L))) as EntityHandoverAck; assertEquals(listOf(1L, 2L), a.spawned)
    }
}
